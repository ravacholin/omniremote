@Composable
fun RemoteTouchpad(
    deviceType: DeviceType,
    onKeyPress: (RemoteKey) -> Unit,
    modifier: Modifier = Modifier
) {
    VirtualTrackpad(
        deviceType = deviceType,
        onNavigationCommand = { command ->
            onKeyPress(command.remoteKey)
        },
        onKeyPress = onKeyPress,
        modifier = modifier
    )
}
